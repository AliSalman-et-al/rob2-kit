def test_build_fingerprint_changes_when_runner_or_preparer_changes(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    _run_dir, baseline = _invoke_failed_run(tmp_path / "baseline", monkeypatch, mode="exit")
    runner_bytes = RUNNER_PATH.read_bytes() + b"\n# build fingerprint probe\n"
    _run_dir, changed_runner = _invoke_failed_run(
        tmp_path / "runner-change", monkeypatch, mode="exit", runner_bytes=runner_bytes
    )
    preparer_bytes = PREPARER_PATH.read_bytes() + b"\n# build fingerprint probe\n"
    _run_dir, changed_preparer = _invoke_failed_run(
        tmp_path / "preparer-change", monkeypatch, mode="exit", preparer_bytes=preparer_bytes
    )

    assert changed_runner["build_sha256"] != baseline["build_sha256"]
    assert changed_preparer["build_sha256"] != baseline["build_sha256"]
    contract_bytes = CONTRACT_PATH.read_bytes() + b"\n# build fingerprint probe\n"
    _run_dir, changed_contract = _invoke_failed_run(
        tmp_path / "contract-change", monkeypatch, mode="exit", contract_bytes=contract_bytes
    )
    assert changed_contract["build_sha256"] != baseline["build_sha256"]


