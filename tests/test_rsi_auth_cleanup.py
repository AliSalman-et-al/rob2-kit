def _invoke_failed_run(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    *,
    mode: str,
    relative_run_dir: bool = False,
    runner_bytes: bytes | None = None,
    preparer_bytes: bytes | None = None,
    contract_bytes: bytes | None = None,
    package_cache: bool = False,
    require_isolated_host: bool = False,
    simulate_posix_isolation: bool = False,
) -> tuple[Path, dict[str, Any]]:
    repo = tmp_path / "fake-repo"
    scripts = repo / "scripts"
    package = repo / "src" / "rob2_kit"
    executable = repo / ".venv" / "Scripts" / "rob2.exe"
    scripts.mkdir(parents=True)
    package.mkdir(parents=True)
    if package_cache:
        cache = package / "__pycache__"
        cache.mkdir()
        (cache / "generated.cpython-313.pyc").write_bytes(b"generated bytecode")
    (scripts / "run_rsi_case.py").write_bytes(runner_bytes or RUNNER_PATH.read_bytes())
    (scripts / "prepare_rsi_workspace.py").write_bytes(preparer_bytes or PREPARER_PATH.read_bytes())
    (scripts / "benchmark_contract.py").write_bytes(contract_bytes or CONTRACT_PATH.read_bytes())
    (scripts / "benchmark_recovery_exec_allowlist.json").write_bytes(
        (SCRIPTS / "benchmark_recovery_exec_allowlist.json").read_bytes()
    )
    (package / "__init__.py").write_text("", encoding="utf-8")
    (repo / "pyproject.toml").write_text("project = {}\n", encoding="utf-8")
    (repo / "uv.lock").write_text("version = 1\n", encoding="utf-8")
    executable.parent.mkdir(parents=True)
    executable.write_bytes(b"fake rob2 executable")
    codex_executable = repo / "codex"
    codex_executable.write_bytes(b"fake codex executable")

    run_dir = tmp_path / "attempt"
    case = tmp_path / "unused-case.json"
    case.write_text("{}", encoding="utf-8")
    prompt = tmp_path / "prompt.txt"
    prompt.write_text("Continue.\n", encoding="utf-8")
    fake_home = tmp_path / "fake-user-home"
    auth_source = fake_home / ".codex" / "auth.json"
    auth_source.parent.mkdir(parents=True)
    auth_source.write_text('{"fake":"test-only"}', encoding="utf-8")
    monkeypatch.setattr(Path, "home", classmethod(lambda _cls: fake_home))
    monkeypatch.setenv("HOME", str(fake_home))
    monkeypatch.setenv("CODEX_EXECUTABLE", str(codex_executable))
    if relative_run_dir:
        monkeypatch.chdir(tmp_path)

    def prepare_workspace(_case: Path, workspace: Path) -> dict[str, Any]:
        workspace.mkdir(parents=True)
        (workspace / "input").mkdir()
        skill = workspace / ".agents" / "skills" / "rob2-assess"
        skill.mkdir(parents=True)
        (skill / "SKILL.md").write_text("test skill", encoding="utf-8")
        return {
            "schema": "rob2-kit.rsi-run-inputs.v1",
            "trial": "trial-a",
            "approved_scope": None,
            "expected_result": {
                "trial": "trial-a",
                "comparison": [
                    {"id": "A", "assignment": "treatment"},
                    {"id": "B", "assignment": "control"},
                ],
                "endpoint_definition": "death from any cause",
                "population": "all randomized participants",
                "window": "36 months",
                "reported_scope": {
                    "form": "comparative_effect",
                    "analysis_population": "all randomized participants",
                    "endpoint": {"definition": "death from any cause"},
                    "effect_measure": "hazard_ratio",
                    "estimate": "HR 0.75",
                    "precision": "95% CI 0.55 to 1.02",
                },
            },
        }

    monkeypatch.syspath_prepend(str(SCRIPTS))
    runner = runpy.run_path(str(RUNNER_PATH))
    runner_globals = runner["main"].__globals__
    runner_globals["__file__"] = str(scripts / "run_rsi_case.py")
    runner_globals["prepare_workspace"] = prepare_workspace

    def probe_server_inventory(command: Path, workspace: Path) -> dict[str, Any]:
        names = sorted(runner_globals["EXPECTED_TOOL_INVENTORY"])
        binding = {
            "server": "rob2",
            "command": str(command.resolve()),
            "args": ["mcp"],
            "workspace_sha256": hashlib.sha256(
                str(workspace.resolve()).encode("utf-8")
            ).hexdigest(),
        }
        return {
            "status": "verified",
            "source": "stdio tools/list",
            "server": "rob2",
            "names": names,
            "tool_count": len(names),
            "server_binding": binding,
        }

    runner_globals["probe_server_advertised_inventory"] = probe_server_inventory
    runner_globals["_terminate_owned_process"] = lambda _process, **_kwargs: None
    if simulate_posix_isolation or require_isolated_host:
        runner_globals["_is_windows"] = lambda: False
        runner_globals["_preflight_isolation"] = lambda _command, _required: {
            "requested": True,
            "supported": True,
            "sentinel": "denied",
        }
    monkeypatch.setattr(
        sys,
        "argv",
        [
            str(RUNNER_PATH),
            "--case",
            str(case),
            "--prompt",
            str(prompt),
            "--run-dir",
            "attempt" if relative_run_dir else str(run_dir),
            "--phase",
            "1",
        ],
    )
    if require_isolated_host:
        sys.argv.append("--require-isolated-host")

    calls = 0

    def fake_run(command: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        nonlocal calls
        calls += 1
        if "export-skill" in command:
            return subprocess.CompletedProcess(command, 0)
        if command[-1:] == ["mcp"]:
            from rob2_kit.interfaces.mcp.server import mcp

            async def list_tools() -> list[dict[str, Any]]:
                tools = await mcp.list_tools()
                inventory = []
                for tool in tools:
                    annotations = tool.annotations
                    inventory.append(
                        {
                            "name": tool.name,
                            "title": tool.title,
                            "description": tool.description,
                            "inputSchema": tool.parameters,
                            "outputSchema": tool.output_schema,
                            "annotations": {
                                "readOnlyHint": (
                                    annotations.read_only_hint if annotations is not None else False
                                ),
                                "destructiveHint": (
                                    annotations.destructive_hint
                                    if annotations is not None
                                    else False
                                ),
                                "idempotentHint": (
                                    annotations.idempotent_hint
                                    if annotations is not None
                                    else False
                                ),
                                "openWorldHint": (
                                    annotations.open_world_hint
                                    if annotations is not None
                                    else False
                                ),
                            },
                        }
                    )
                return inventory

            response = [
                {
                    "jsonrpc": "2.0",
                    "id": 1,
                    "result": {"serverInfo": {"name": "rob2", "version": "test"}},
                },
                {
                    "jsonrpc": "2.0",
                    "id": 2,
                    "result": {"tools": asyncio.run(list_tools())},
                },
            ]
            return subprocess.CompletedProcess(
                command,
                0,
                stdout="\n".join(json.dumps(item) for item in response) + "\n",
                stderr="",
            )
        environment = kwargs["env"]
        codex_home = Path(environment["CODEX_HOME"])
        assert codex_home.is_absolute()
        isolated_auth = codex_home / "auth.json"
        assert isolated_auth.read_text(encoding="utf-8") == '{"fake":"test-only"}'
        # Stand in for files written by the failed Codex process. Cleanup must
        # remove only the temporary credential copy and keep these run outputs.
        (codex_home / "session-state.db").write_bytes(b"fake session state")
        kwargs["stdout"].write(b'{"type":"turn.failed"}\n')
        kwargs["stderr"].write(b"synthetic failure\n")
        last_message = Path(command[command.index("--output-last-message") + 1])
        last_message.write_text("partial output", encoding="utf-8")
        if mode == "raise":
            raise OSError("synthetic Codex launch failure")
        return subprocess.CompletedProcess(command, 17)

    monkeypatch.setattr(subprocess, "run", fake_run)
    monkeypatch.setattr(subprocess, "check_output", lambda *args, **kwargs: "fake-commit")

    class FakePopen:
        def __init__(self, command: list[str], **kwargs: Any) -> None:
            nonlocal calls
            calls += 1
            self.command = command
            self.kwargs = kwargs
            self.returncode: int | None = None
            if require_isolated_host:
                environment = kwargs["env"]
                assert "ROB2_RSI_PREFLIGHT_SECRET" not in environment
                assert "OPENAI_API_KEY" not in environment

        def communicate(
            self, input: bytes | None = None, timeout: float | None = None
        ) -> tuple[bytes, bytes]:
            del input
            del timeout
            environment = self.kwargs["env"]
            codex_home = Path(environment["CODEX_HOME"])
            assert codex_home.is_absolute()
            isolated_auth = codex_home / "auth.json"
            assert isolated_auth.read_text(encoding="utf-8") == '{"fake":"test-only"}'
            (codex_home / "session-state.db").write_bytes(b"fake session state")
            self.kwargs["stdout"].write(b'{"type":"turn.failed"}\n')
            self.kwargs["stderr"].write(b"synthetic failure\n")
            last_message = Path(self.command[self.command.index("--output-last-message") + 1])
            last_message.write_text("partial output", encoding="utf-8")
            if mode == "raise":
                raise OSError("synthetic Codex launch failure")
            self.returncode = 17
            return b"", b""

        def poll(self) -> int | None:
            return self.returncode

        def kill(self) -> None:
            self.returncode = -9

        def wait(self) -> int | None:
            return self.returncode

    monkeypatch.setattr(subprocess, "Popen", FakePopen)
    runner["main"].__globals__["_windows_job_guard"] = lambda _process: None
    if mode == "raise":
        with pytest.raises(OSError, match="synthetic Codex launch failure"):
            runner["main"]()
    else:
        with pytest.raises(SystemExit) as error:
            runner["main"]()
        assert error.value.code == 17
    assert calls == 2
    assert auth_source.read_text(encoding="utf-8") == '{"fake":"test-only"}'
    metadata = json.loads((run_dir / "phase-1.meta.json").read_text(encoding="utf-8"))
    return run_dir, metadata


@pytest.mark.parametrize("mode", ["exit", "raise"])
def test_failed_codex_run_removes_only_isolated_auth_copy(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, mode: str
) -> None:
    runner = runpy.run_path(str(RUNNER_PATH))
    stale_home = runner["_codex_home_path"](tmp_path / "attempt")
    stale_home.mkdir(mode=0o700, parents=True, exist_ok=True)
    (stale_home / "auth.json").write_text('{"stale":"credential"}', encoding="utf-8")
    run_dir, metadata = _invoke_failed_run(tmp_path, monkeypatch, mode=mode)
    codex_home = Path(metadata["runtime_inputs"]["codex_home_path"])

    assert not (run_dir / "codex-home").exists()
    assert not (codex_home / "auth.json").exists()
    assert (codex_home / "session-state.db").read_bytes() == b"fake session state"
    assert (run_dir / "phase-1.jsonl").read_bytes() == b'{"type":"turn.failed"}\n'
    assert (run_dir / "phase-1.stderr.txt").read_bytes() == b"synthetic failure\n"
    assert (run_dir / "phase-1.last-message.txt").read_text(encoding="utf-8") == "partial output"
    assert (run_dir / "phase-1.meta.json").is_file()


