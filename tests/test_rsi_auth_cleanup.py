@pytest.mark.skipif(os.name == "nt", reason="strict host isolation requires a POSIX host")
def test_required_host_isolation_records_a_deny_by_default_profile(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    run_dir, metadata = _invoke_failed_run(
        tmp_path, monkeypatch, mode="exit", require_isolated_host=True
    )

    profile = (Path(metadata["runtime_inputs"]["codex_home_path"]) / "config.toml").read_text(
        encoding="utf-8"
    )
    assert 'default_permissions = "rob2-rsi"' in profile
    assert '":root" = "deny"' in profile
    protected_paths = (run_dir, Path(tempfile.gettempdir()), Path.home() / ".codex")
    for path in protected_paths:
        assert f'{json.dumps(path.as_posix())} = "deny"' in profile
    assert metadata["host_isolation"] == {
        "required": True,
        "policy": "deny-by-default",
    }


_PROTECTED_PROBE_NAMES = (
    "sentinel",
    "run_inputs",
    "approved_scope",
    "codex_auth",
    "execution",
    "source_auth",
    "sibling_codex_auth",
    "sibling_run_inputs",
    "outside_temp",
)
_ALL_PROBE_DENIALS = "ENV:clean\nALLOWED:read_write\n" + "".join(
    f"DENIED:{name}\nDENIED_WRITE:{name}\n" for name in _PROTECTED_PROBE_NAMES
)


@pytest.mark.parametrize(
    "probe_output, expected_error",
    [
        (_ALL_PROBE_DENIALS, None),
        (
            _ALL_PROBE_DENIALS.replace("DENIED:codex_auth\n", "READ:codex_auth\n"),
            "a protected file was readable",
        ),
        (
            _ALL_PROBE_DENIALS.replace("DENIED:sibling_run_inputs\n", ""),
            "did not deny protected files: sibling_run_inputs",
        ),
        (
            _ALL_PROBE_DENIALS.replace("ALLOWED:read_write", "ALLOWED:denied"),
            "did not verify workspace read/write access",
        ),
    ],
)
def test_isolation_preflight_probes_run_inputs_approved_scope_and_auth(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    probe_output: str,
    expected_error: str | None,
) -> None:
    runner = runpy.run_path(str(RUNNER_PATH))
    monkeypatch.setitem(runner["_preflight_isolation"].__globals__, "_is_windows", lambda: False)
    monkeypatch.setenv("ROB2_RSI_PREFLIGHT_SECRET", "test-secret")
    monkeypatch.setenv("OPENAI_API_KEY", "test-api-key")
    captured_profile: dict[str, str] = {}

    def fake_check_output(command: list[str], **kwargs: Any) -> str:
        if command[1] == "sandbox":
            config = Path(kwargs["env"]["CODEX_HOME"]) / "config.toml"
            captured_profile["text"] = config.read_text(encoding="utf-8")
            assert Path(kwargs["env"]["TMPDIR"]) == Path(kwargs["cwd"]) / ".tmp"
            assert kwargs["env"]["TMP"] == kwargs["env"]["TMPDIR"]
            assert kwargs["env"]["TEMP"] == kwargs["env"]["TMPDIR"]
            assert "ROB2_RSI_PREFLIGHT_SECRET" not in kwargs["env"]
            assert "OPENAI_API_KEY" not in kwargs["env"]
            return probe_output
        return "Codex test version"

    monkeypatch.setattr(subprocess, "check_output", fake_check_output)
    if expected_error is None:
        result = runner["_preflight_isolation"](Path("codex"), True)
        assert result["sentinel"] == "denied"
    else:
        with pytest.raises(RuntimeError, match=expected_error):
            runner["_preflight_isolation"](Path("codex"), True)

    profile = captured_profile["text"]
    deny_lines = [line for line in profile.splitlines() if line.endswith(' = "deny"')]
    assert any(line.endswith('/run-inputs.json" = "deny"') for line in deny_lines)
    assert any(line.endswith('/approved-scope.json" = "deny"') for line in deny_lines)
    assert any(line.endswith('/auth.json" = "deny"') for line in deny_lines)
    assert any(line.endswith('/forbidden sentinel.txt" = "deny"') for line in deny_lines)
    assert '":tmpdir" = "write"' not in profile
    assert '":slash_tmp" = "write"' not in profile
    environment = runner["_codex_environment"](
        Path("/tmp/codex"), Path("/tmp/workspace"), strict=True, base={"PATH": "bin"}
    )
    assert environment["TMPDIR"] == "/tmp/workspace/.tmp"


