def test_low_risk_trial_is_assessed_finalized_and_verified(agent: Agent) -> None:
    agent.prepare(OUTCOME)
    agent.read_required()
    agent.propose(selection(agent))
    agent.approve()
    agent.read_required()

    answers = low_risk_answers(agent)
    for domain_id, domain_answers in answers.items():
        context = agent.context()
        assert context["domain_id"] == domain_id
        saved = agent.save_domain(domain_id, domain_answers)
        assert saved["outcome"] == "success", saved
        assert saved["data"]["checkpoint"]["judgment"] == "low"

    agent.close_trials()
    finalized = agent.finalize()
    summary = finalized["data"]["assessment_summary"]["prevent-tia"]
    assert summary["overall"] == "low"
    assert set(summary["domains"].values()) == {"low"}

    bundle = agent.workspace / finalized["data"]["artifact"]["path"]
    assert rob2(agent.workspace, "verify", str(bundle)).returncode == 0
    standalone = subprocess.run(
        [sys.executable, "scripts/verify_bundle.py", str(bundle)],
        capture_output=True,
        text=True,
        cwd=REPO,
        check=False,
    )
    assert standalone.returncode == 0, standalone.stdout + standalone.stderr
