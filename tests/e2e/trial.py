def build(root: Path, label: str = "prevent-tia") -> Path:
    """Write the dossier under root/input/<label> and return the workspace root."""
    trial = root / "input" / label
    trial.mkdir(parents=True, exist_ok=True)
    document = pymupdf.open()
    for text in MAIN_PAGES:
        page = document.new_page()
        page.insert_textbox(pymupdf.Rect(50, 50, 560, 800), text, fontsize=9)
    document.save(trial / "main.pdf")
    (trial / "protocol.txt").write_text(PROTOCOL, encoding="utf-8")
    replay = json.dumps(REGISTRY).encode("utf-8")
    (trial / "registry.json").write_bytes(replay)
    (trial / "sources.toml").write_text(
        '[roles]\n"main.pdf" = "main_article"\n"protocol.txt" = "protocol"\n\n'
        f'[registry]\nnct = "{NCT}"\nreplay = "registry.json"\n'
        'captured_at = "2024-01-15T00:00:00Z"\n'
        f'sha256 = "{hashlib.sha256(replay).hexdigest()}"\n'
        'provenance = "Retained ClinicalTrials.gov API v2 response (fictional E2E fixture)"\n',
        encoding="utf-8",
    )
    return root


OPEN_LABEL = """Arthroscopic surgery versus physiotherapy for knee pain: an open-label trial
Methods: 200 adults with degenerative knee pain were randomised (1:1) to arthroscopic
surgery or a 12-week physiotherapy programme. The allocation sequence was generated with
a computer random number generator. Allocation used envelopes held by the recruiting
surgeon. Neither participants nor clinicians were blinded.
The primary outcome was knee pain on a 0 to 10 numerical rating scale, reported by
participants at 12 months.
Eight participants allocated to physiotherapy were disappointed with their allocation and
obtained private surgery during the trial.
Results: Pain at 12 months was available for 78 of 100 surgery participants and 88 of
100 physiotherapy participants. Withdrawals in the surgery group were mainly for lack of
improvement. The analysis included only participants who completed their allocated
treatment (per-protocol).
Table 2. Knee pain at 12 months (0 to 10)
Mean difference -1.2 (95% CI -2.0 to -0.4)
Baseline characteristics were similar between groups."""


