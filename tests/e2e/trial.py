"""A realistic, fictional two-arm trial dossier built at test time.

The main report is a three-page PDF, the protocol a text supplement, and the
ClinicalTrials.gov record a retained replay, so intake never touches the network.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pymupdf

NCT = "NCT04123456"

MAIN_PAGES = (
    """Apixaban versus aspirin after transient ischaemic attack: the PREVENT-TIA randomised trial
Background: Recurrent stroke after transient ischaemic attack remains common.
Methods: In this double-blind, placebo-controlled trial at 42 hospitals, adults with a
transient ischaemic attack within 7 days were randomly assigned (1:1) to apixaban 5 mg
twice daily or aspirin 100 mg daily for 12 months. The trial is registered with
ClinicalTrials.gov, NCT04123456.
Randomisation and masking
The allocation sequence was computer generated by an independent statistician using
permuted blocks of four, stratified by centre. Investigators enrolled participants and
obtained allocation through a central interactive web response system after eligibility
was confirmed. Apixaban and aspirin were supplied as identical over-encapsulated tablets
with matching placebo (double dummy). Participants, investigators, site staff and outcome
assessors were masked to treatment assignment.
Outcomes
The primary outcome was recurrent stroke (ischaemic or haemorrhagic) within 12 months,
adjudicated by a central committee masked to treatment assignment using brain imaging
and clinical records. The primary safety outcome was major bleeding.""",
    """Statistical analysis
The primary analysis followed the intention-to-treat principle and included all randomised
participants. Hazard ratios were estimated with Cox proportional hazards models stratified
by centre. Participants lost to follow-up were censored at last contact. The statistical
analysis plan was finalised on 3 March 2020, before enrolment began and before any
unmasking of data.
Results
Between 1 April 2020 and 30 June 2022, 1204 participants were randomly assigned:
602 to apixaban and 602 to aspirin. Baseline characteristics were similar between groups
(Table 1). Twelve-month follow-up was complete for 596 participants in the apixaban group
and 597 in the aspirin group; six and five participants respectively were lost to
follow-up. Adherence to study drug was 91% in both groups.
Table 2. Primary outcome
Recurrent stroke within 12 months: apixaban 31/602 (5.1%); aspirin 52/602 (8.6%)
Hazard ratio 0.59 (95% CI 0.38 to 0.92); p=0.020""",
    """Table 1. Baseline characteristics
Mean age, years: apixaban 68.2; aspirin 68.0
Women: apixaban 41%; aspirin 42%
Hypertension: apixaban 71%; aspirin 70%
Discussion
Apixaban reduced recurrent stroke compared with aspirin after transient ischaemic attack.
Major bleeding occurred in 9 participants given apixaban and 6 given aspirin.
Funding: national research council. The funder had no role in the trial.""",
)

PROTOCOL = """PREVENT-TIA protocol, version 2.0, 3 March 2020
Primary outcome: recurrent stroke (ischaemic or haemorrhagic) within 12 months of
randomisation, adjudicated centrally by assessors masked to allocation.
Primary analysis: intention-to-treat, Cox proportional hazards model stratified by centre,
reported as a hazard ratio with 95% confidence interval. No other measure or analysis of
the primary outcome is planned.
"""

